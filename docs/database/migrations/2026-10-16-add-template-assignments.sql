CREATE TABLE IF NOT EXISTS workout_template_assignments
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_template_id BIGINT      NOT NULL,
    user_id             BIGINT      NOT NULL,
    assigned_by_id      BIGINT      NOT NULL,
    position            INTEGER     NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_workout_template_assignments_template
        FOREIGN KEY (workout_template_id) REFERENCES workout_templates (id) ON DELETE CASCADE,
    CONSTRAINT fk_workout_template_assignments_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_workout_template_assignments_assigned_by
        FOREIGN KEY (assigned_by_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_workout_template_assignments_template_user
        UNIQUE (workout_template_id, user_id),
    CONSTRAINT ck_workout_template_assignments_position
        CHECK (position >= 0)
);

CREATE INDEX IF NOT EXISTS ix_workout_template_assignments_user_position
    ON workout_template_assignments (user_id, position);

INSERT INTO workout_template_assignments (
    workout_template_id,
    user_id,
    assigned_by_id,
    position
)
SELECT template.id,
       template.owner_id,
       template.owner_id,
       template.position
FROM workout_templates AS template
ON CONFLICT (workout_template_id, user_id) DO NOTHING;

GRANT SELECT, INSERT, UPDATE, DELETE ON workout_template_assignments TO setforge_app;
GRANT USAGE, SELECT ON SEQUENCE workout_template_assignments_id_seq TO setforge_app;
